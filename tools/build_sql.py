"""Generates the pasteable SQL from source, so Snowsight gets exactly the code the tests run.

    python tools/build_sql.py

Writes sql/05_glossary.sql (from glossary/terms.yaml) and sql/06_procedures.sql (from python/).
Both are generated files: edit the sources, then rerun this.
"""
import json
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
SESSION = """USE ROLE SVC_MAPPER;
USE SECONDARY ROLES NONE;
USE WAREHOUSE SVC_WH;
USE SCHEMA SVC_APP.MAPPER;
"""

PROCEDURES = [
    {
        "module": "profile_estate.py",
        "signature": "PROFILE_ESTATE(RAW_DB STRING DEFAULT 'ALDERGLEN_RAW')",
    },
    {
        "module": "map_term.py",
        "signature": "MAP_TERM(TERM_ID STRING, MODEL STRING DEFAULT 'CLAUDE-SONNET-5', "
                     "USE_HISTORY BOOLEAN DEFAULT TRUE, RAW_DB STRING DEFAULT 'ALDERGLEN_RAW', "
                     "HISTORY_TAG STRING DEFAULT NULL)",
    },
    {
        # Reuses the interview's own completeness and identifier checks, so promotion applies
        # exactly the rules the app enforced.
        "module": "promote_term.py",
        "extra": ["interview.py"],
        "signature": "PROMOTE_TERM(DRAFT_ID STRING, TERM_ID STRING, APP_DB STRING DEFAULT 'SVC_APP')",
    },
]


def handler_source(module: str, extra=()) -> str:
    """common.py (and any extra modules) inlined ahead of the module: stored procedures cannot import
    sibling files."""
    parts = ["common.py", *extra, module]
    src = "\n\n".join((ROOT / "python" / name).read_text() for name in parts)
    if "$$" in src:
        raise ValueError(f"{module} contains $$, which would end the procedure body")
    return src


def header(name: str, source: str) -> str:
    return (f"/*\n  {name}\n  GENERATED by tools/build_sql.py from {source}. Do not edit; edit the source and rerun.\n"
            "  Run as SVC_MAPPER with secondary roles off (the lines below do that).\n*/\n\n")


def glossary_sql() -> str:
    terms = yaml.safe_load((ROOT / "glossary" / "terms.yaml").read_text())["terms"]
    out = [header("05_glossary.sql", "glossary/terms.yaml"), SESSION,
           "\nCREATE OR REPLACE TABLE GLOSSARY (TERM_ID STRING, TERM VARIANT, LOADED_AT TIMESTAMP_LTZ);\n"]
    for t in terms:
        body = json.dumps(t, indent=2, ensure_ascii=False)
        if "$$" in body:
            raise ValueError(f"{t['id']} contains $$")
        out.append(f"\nINSERT INTO GLOSSARY SELECT '{t['id']}', PARSE_JSON($${body}$$), CURRENT_TIMESTAMP();\n")
    out.append("\nSELECT TERM_ID, TERM:term::STRING AS TERM, TERM:owner::STRING AS OWNER FROM GLOSSARY ORDER BY 1;\n")
    return "".join(out)


def procedures_sql() -> str:
    out = [header("06_procedures.sql", "python/"), SESSION, """
CREATE TABLE IF NOT EXISTS PROPOSALS (
  RUN_ID STRING, CREATED_AT TIMESTAMP_LTZ, TERM_ID STRING, MODEL STRING, USE_HISTORY BOOLEAN,
  PROMPT_CHARS NUMBER, HISTORY_QUERIES NUMBER, PROPOSAL VARIANT, USAGE VARIANT,
  MEASURE_SQL STRING, MEASURE_VALUE FLOAT, MEASURE_ERROR STRING, NOTE STRING
);
"""]
    out.append("""
-- Earlier versions had no HISTORY_TAG argument. Drop that signature so a call is never ambiguous.
DROP PROCEDURE IF EXISTS MAP_TERM(STRING, STRING, BOOLEAN, STRING);

-- One row per interview draft promoted into GLOSSARY. The mapper never writes the drafts themselves.
CREATE TABLE IF NOT EXISTS PROMOTIONS (DRAFT_ID STRING, TERM_ID STRING, PROMOTED_AT TIMESTAMP_LTZ);
""")
    for p in PROCEDURES:
        out.append(f"""
CREATE OR REPLACE PROCEDURE {p['signature']}
  RETURNS VARIANT
  LANGUAGE PYTHON
  RUNTIME_VERSION = '3.11'
  PACKAGES = ('snowflake-snowpark-python')
  HANDLER = 'main'
  EXECUTE AS CALLER
AS
$$
{handler_source(p['module'], p.get('extra', ()))}
$$;
""")
    return "".join(out)


if __name__ == "__main__":
    (ROOT / "sql" / "05_glossary.sql").write_text(glossary_sql())
    (ROOT / "sql" / "06_procedures.sql").write_text(procedures_sql())
    print("Wrote sql/05_glossary.sql and sql/06_procedures.sql")
