"""Builds app/interview_app.py: python/interview.py inlined above app/ui.py, one file to paste into a
Streamlit in Snowflake app (no CLI, no stage upload). Run: python tools/build_app.py"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
HEADER = ("# GENERATED by tools/build_app.py from python/interview.py and app/ui.py. Do not edit; edit the\n"
          "# sources and rerun. Paste this whole file into a Streamlit in Snowflake app running as SVC_INTERVIEWER.\n\n")


def build() -> str:
    logic = (ROOT / "python" / "interview.py").read_text()
    ui = (ROOT / "app" / "ui.py").read_text()
    return HEADER + logic.rstrip() + "\n\n\n" + ui


if __name__ == "__main__":
    (ROOT / "app" / "interview_app.py").write_text(build())
    print("Wrote app/interview_app.py")
