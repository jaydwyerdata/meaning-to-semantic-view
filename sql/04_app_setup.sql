/*
  04_app_setup.sql
  Creates the tool's own database and two roles that keep the mapper away from the answer key.
  Run once as ACCOUNTADMIN, after 01 and 02. See ADR-012.

  SVC_MAPPER     reads the estate, query history and Cortex; owns SVC_APP.MAPPER; cannot see EVAL.
  SVC_EVALUATOR  reads the estate and the mapper's output; owns SVC_APP.EVAL (answer key, scores).
*/

SET RAW_DB = 'ALDERGLEN_RAW';
SET APP_DB = 'SVC_APP';
SET WH_NAME = 'SVC_WH';
SET ME = CURRENT_USER();

USE ROLE ACCOUNTADMIN;

CREATE ROLE IF NOT EXISTS SVC_MAPPER;
CREATE ROLE IF NOT EXISTS SVC_EVALUATOR;
GRANT ROLE SVC_MAPPER TO ROLE SYSADMIN;
GRANT ROLE SVC_EVALUATOR TO ROLE SYSADMIN;
GRANT ROLE SVC_MAPPER TO USER IDENTIFIER($ME);
GRANT ROLE SVC_EVALUATOR TO USER IDENTIFIER($ME);

-- Tool database: one schema per role.
CREATE DATABASE IF NOT EXISTS IDENTIFIER($APP_DB);
USE DATABASE IDENTIFIER($APP_DB);
CREATE SCHEMA IF NOT EXISTS MAPPER;
CREATE SCHEMA IF NOT EXISTS EVAL;
GRANT USAGE ON DATABASE IDENTIFIER($APP_DB) TO ROLE SVC_MAPPER;
GRANT USAGE ON DATABASE IDENTIFIER($APP_DB) TO ROLE SVC_EVALUATOR;
GRANT OWNERSHIP ON SCHEMA MAPPER TO ROLE SVC_MAPPER COPY CURRENT GRANTS;
GRANT OWNERSHIP ON SCHEMA EVAL TO ROLE SVC_EVALUATOR COPY CURRENT GRANTS;

-- The evaluator reads the mapper's output; the mapper gets nothing on EVAL.
GRANT USAGE ON SCHEMA MAPPER TO ROLE SVC_EVALUATOR;
GRANT SELECT ON FUTURE TABLES IN SCHEMA MAPPER TO ROLE SVC_EVALUATOR;
GRANT SELECT ON FUTURE VIEWS IN SCHEMA MAPPER TO ROLE SVC_EVALUATOR;
GRANT SELECT ON FUTURE SEMANTIC VIEWS IN SCHEMA MAPPER TO ROLE SVC_EVALUATOR;

-- Both read the estate.
GRANT USAGE ON DATABASE IDENTIFIER($RAW_DB) TO ROLE SVC_MAPPER;
GRANT USAGE ON DATABASE IDENTIFIER($RAW_DB) TO ROLE SVC_EVALUATOR;
GRANT USAGE ON ALL SCHEMAS IN DATABASE IDENTIFIER($RAW_DB) TO ROLE SVC_MAPPER;
GRANT USAGE ON ALL SCHEMAS IN DATABASE IDENTIFIER($RAW_DB) TO ROLE SVC_EVALUATOR;
GRANT SELECT ON ALL TABLES IN DATABASE IDENTIFIER($RAW_DB) TO ROLE SVC_MAPPER;
GRANT SELECT ON ALL TABLES IN DATABASE IDENTIFIER($RAW_DB) TO ROLE SVC_EVALUATOR;

-- Compute, Cortex, and (mapper only) account query history.
GRANT USAGE ON WAREHOUSE IDENTIFIER($WH_NAME) TO ROLE SVC_MAPPER;
GRANT USAGE ON WAREHOUSE IDENTIFIER($WH_NAME) TO ROLE SVC_EVALUATOR;
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_USER TO ROLE SVC_MAPPER;
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_USER TO ROLE SVC_EVALUATOR;
GRANT DATABASE ROLE SNOWFLAKE.GOVERNANCE_VIEWER TO ROLE SVC_MAPPER;

-- Check: the mapper role must not be able to see EVAL.
SHOW GRANTS TO ROLE SVC_MAPPER;
