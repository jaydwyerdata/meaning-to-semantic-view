    status, term = rows[0][0], rows[0][1]
    if status != "CONFIRMED":
        raise ValueError(f"Draft {draft_id} is {status}: only a draft the business user confirmed can be promoted")
    draft = json.loads(term) if isinstance(term, str) else term

